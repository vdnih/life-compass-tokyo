import 'package:flutter/foundation.dart';

/// 依存関係の強度
///
/// - `hard`: 物理的・法的・論理的に成立しない順序の前提（赤フィードバック）
/// - `soft`: 慣習・準備期間として推奨される前提（黄フィードバック）
///
/// いずれも配置はブロックしない（Value 4: Empowerment, not Direction）
enum DependencyStrength {
  hard,
  soft;
}

/// イベント間の依存関係を表すイミュータブルなモデル（v6.0）
///
/// v6.0 変更点:
/// - `strength` (DependencyStrength) フィールドを追加
@immutable
class EventDependency {
  /// 依存関係の一意識別子
  final String id;

  /// 依存元イベントID
  final String sourceEventId;

  /// 依存先イベントID
  final String targetEventId;

  /// ソースからターゲットへの月数オフセット
  final int offsetMonths;

  /// テンプレートから自動生成されたか
  final bool isAutoGenerated;

  /// 依存関係の強度（hard または soft）
  final DependencyStrength strength;

  const EventDependency({
    required this.id,
    required this.sourceEventId,
    required this.targetEventId,
    required this.offsetMonths,
    this.isAutoGenerated = false,
    this.strength = DependencyStrength.soft,
  });

  /// 一部のプロパティを変更した新しい [EventDependency] インスタンスを生成する
  EventDependency copyWith({
    String? id,
    String? sourceEventId,
    String? targetEventId,
    int? offsetMonths,
    bool? isAutoGenerated,
    DependencyStrength? strength,
  }) {
    return EventDependency(
      id: id ?? this.id,
      sourceEventId: sourceEventId ?? this.sourceEventId,
      targetEventId: targetEventId ?? this.targetEventId,
      offsetMonths: offsetMonths ?? this.offsetMonths,
      isAutoGenerated: isAutoGenerated ?? this.isAutoGenerated,
      strength: strength ?? this.strength,
    );
  }

  /// Firestore 保存用に Map に変換する
  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'sourceEventId': sourceEventId,
      'targetEventId': targetEventId,
      'offsetMonths': offsetMonths,
      'isAutoGenerated': isAutoGenerated,
      'strength': strength.name,
    };
  }

  /// Firestore から取得した Map を [EventDependency] に変換する
  factory EventDependency.fromJson(Map<String, dynamic> json) {
    return EventDependency(
      id: json['id'] as String,
      sourceEventId: json['sourceEventId'] as String,
      targetEventId: json['targetEventId'] as String,
      offsetMonths: (json['offsetMonths'] as num).toInt(),
      isAutoGenerated: (json['isAutoGenerated'] as bool?) ?? false,
      strength: DependencyStrength.values.firstWhere(
        (e) => e.name == json['strength'],
        orElse: () => DependencyStrength.soft,
      ),
    );
  }

  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    return other is EventDependency &&
        other.id == id &&
        other.sourceEventId == sourceEventId &&
        other.targetEventId == targetEventId &&
        other.offsetMonths == offsetMonths &&
        other.isAutoGenerated == isAutoGenerated &&
        other.strength == strength;
  }

  @override
  int get hashCode {
    return id.hashCode ^
        sourceEventId.hashCode ^
        targetEventId.hashCode ^
        offsetMonths.hashCode ^
        isAutoGenerated.hashCode ^
        strength.hashCode;
  }
}
